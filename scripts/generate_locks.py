#!/usr/bin/env python3
"""Generate the macOS 13 / Intel / Python 3.11 wheel lock files (hashes + URLs).

The 2.0 core has no third-party runtime dependencies. The lock files pin the
build/test toolchain so a clean venv install is reproducible and auditable:

* ``requirements/build-lock-macos13-x86_64-py311.txt`` – setuptools + wheel used
  with ``--no-build-isolation`` to build the sdist/wheel deterministically;
* ``requirements/test-lock-macos13-x86_64-py311.txt`` – pytest and its pure
  Python dependencies used to run the contract/core suites.

Run this script from a network-enabled development session only; the resulting
lock files are then installable with ``pip install --require-hashes -r ...``.
The script never imports the product and never touches production paths.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
GROUPS = {
    "build": ["setuptools==79.0.1", "wheel==0.45.1"],
    "test": ["pytest==9.2.0"],
    # Optional legacy KW 1.x environment (MCP server). Kept separate from the
    # zero-dependency core; pinned to versions whose transitive wheels exist for
    # macOS 13 / Intel (cryptography < 50, see pyproject comment).
    "v1": ["mcp>=1.0.0,<2", "cryptography>=3.4,<50", "httpx>=0.27.0", "sqlite-vec>=0.1.0", "pypinyin>=0.50.0", "jieba>=0.42.1"],
}
#: Groups resolved against the local project (extras) instead of PyPI names.
EXTRAS_GROUP = {"v1": ".[v1]"}
#: Groups whose dependency tree contains legitimate pure-Python sdists (jieba);
#: wheels are still preferred over newer sdists (--prefer-binary).
PURE_PYTHON_GROUPS = {"v1"}
HEADER = """# {title}
# Target: macOS 13.x / x86_64 / CPython 3.11 (iMac), no system-site-packages.
# Generated by scripts/generate_locks.py at {generated}; PyPI wheels only.
# Install with: python -m pip install --require-hashes -r {name}
# Core runtime dependencies of knowledge-weaver 2.0: none (standard library only).
"""


def resolve(
    requirements: list[str],
    target: str | None = None,
    binary_flags: tuple[str, ...] = ("--only-binary=:all:",),
) -> list[dict]:
    with tempfile.TemporaryDirectory() as tmp:
        report_path = Path(tmp) / "report.json"
        command = [
            sys.executable,
            "-m",
            "pip",
            "install",
            "--dry-run",
            "--ignore-installed",
            *binary_flags,
            "--report",
            str(report_path),
            *( [target] if target else requirements ),
        ]
        completed = subprocess.run(command, capture_output=True, text=True)
        if completed.returncode != 0:
            raise SystemExit(
                "dependency resolution failed:\n" + completed.stdout + completed.stderr
            )
        report = json.loads(report_path.read_text())
    entries = []
    for item in report["install"]:
        metadata = item["metadata"]
        if metadata["name"].lower() == "knowledge-weaver":
            continue
        download = item.get("download_info", {})
        url = download.get("url", "")
        digest = ""
        archive = download.get("archive_info") or {}
        if archive.get("hash"):
            digest = archive["hash"]
        elif archive.get("hashes"):
            digest = "sha256=" + archive["hashes"]["sha256"]
        entries.append(
            {
                "name": metadata["name"],
                "version": metadata["version"],
                "url": url,
                "hash": digest,
            }
        )
    return sorted(entries, key=lambda entry: entry["name"].lower())


def write_lock(group: str, entries: list[dict]) -> Path:
    path = REPO_ROOT / "requirements" / f"{group}-lock-macos13-x86_64-py311.txt"
    lines = [
        HEADER.format(
            title=f"Unified Memory {group} toolchain lock",
            generated=datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
            name=path.name,
        )
    ]
    for entry in entries:
        digest = entry["hash"].split("=", 1)[1] if "=" in entry["hash"] else entry["hash"]
        lines.append(
            f"# {entry['url']}\n{entry['name']}=={entry['version']} --hash=sha256:{digest}"
        )
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--group", choices=[*GROUPS, "all"], default="all")
    args = parser.parse_args(argv)
    groups = list(GROUPS) if args.group == "all" else [args.group]
    for group in groups:
        flags = ("--prefer-binary",) if group in PURE_PYTHON_GROUPS else ("--only-binary=:all:",)
        entries = resolve(GROUPS[group], EXTRAS_GROUP.get(group), flags)
        path = write_lock(group, entries)
        print(f"{group}: {path.relative_to(REPO_ROOT)} ({len(entries)} packages)")
        for entry in entries:
            print(f"  {entry['name']}=={entry['version']} {entry['hash']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
